#!/usr/bin/env python3
"""Design tokens: verify contrast, then generate Dart, CSS and a contrast report from tokens/tokens.json. Standard library only.

Usage: generate_tokens.py            verify and (re)generate the files
       generate_tokens.py --check    verify, and fail if a generated file is out of date (for CI)
Generated files (commit them):
  packages/design_system/lib/src/tokens.g.dart   Flutter constants
  apps/admin/src/styles/tokens.css               CSS custom properties for the admin dashboard
  docs/design/CONTRAST.md                        every checked colour pair with its ratio
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
SRC = os.path.join(HERE, "..", "tokens", "tokens.json")
OUT = {
    "dart": os.path.join(ROOT, "packages/design_system/lib/src/tokens.g.dart"),
    "css": os.path.join(ROOT, "apps/admin/src/styles/tokens.css"),
    "report": os.path.join(ROOT, "docs/design/CONTRAST.md"),
}
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")


def luminance(hexcolor):
    r, g, b = (int(hexcolor[i:i + 2], 16) / 255 for i in (1, 3, 5))
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def contrast(a, b):
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def validate(tokens):
    """Return a list of problems (empty if the tokens are valid and every pair meets its minimum contrast)."""
    problems = []
    light, dark = tokens["colors"]["light"], tokens["colors"]["dark"]
    if set(light) != set(dark):
        problems.append(f"light and dark define different colour names: {sorted(set(light) ^ set(dark))}")
    for theme, palette in tokens["colors"].items():
        for name, value in palette.items():
            if not HEX.match(value):
                problems.append(f"{theme}.{name}: '{value}' is not a #RRGGBB colour")
    if problems:
        return problems
    for theme, palette in tokens["colors"].items():
        for p in tokens["pairs"]:
            for k in (p["fg"], p["bg"]):
                if k not in palette:
                    problems.append(f"pair uses unknown colour '{k}'")
                    break
            else:
                r = contrast(palette[p["fg"]], palette[p["bg"]])
                if r < p["min"]:
                    problems.append(f"{theme}: {p['fg']} on {p['bg']} is {r:.2f}:1, needs {p['min']}:1 ({p['use']})")
    for k in tokens.get("knownFailures", []):
        pal = tokens["colors"][k["theme"]]
        if contrast(pal[k["fg"]], pal[k["bg"]]) >= k["min"]:
            problems.append(f"knownFailures entry {k['theme']} {k['fg']} on {k['bg']} now PASSES: remove it from knownFailures")
    return problems


def argb(hexcolor):
    return "0xFF" + hexcolor[1:].upper()


def gen_dart(t):
    out = ["// GENERATED by packages/design_system/tools/generate_tokens.py from tokens/tokens.json. Do not edit by hand.",
           "// ignore_for_file: public_member_api_docs", "import 'dart:ui' show Color;", ""]
    for theme in ("light", "dark"):
        out.append(f"abstract final class {theme.capitalize()}Tokens {{")
        for n, v in t["colors"][theme].items():
            out.append(f"  static const Color {n} = Color({argb(v)});")
        out += ["}", ""]
    names = list(t["colors"]["light"])
    out.append("/// One theme's colours as a value, so widgets can read `context.colors.primary` in either theme.")
    out.append("class AppColors {")
    out.append("  const AppColors({")
    out += [f"    required this.{n}," for n in names]
    out += ["  });", ""]
    out += [f"  final Color {n};" for n in names]
    for theme in ("light", "dark"):
        out += ["", f"  static const AppColors {theme} = AppColors("] + [f"    {n}: {theme.capitalize()}Tokens.{n}," for n in names] + ["  );"]
    out += ["}", ""]
    out += ["abstract final class Spacing {"] + [f"  static const double {k} = {float(v)};" for k, v in t["spacing"].items()] + ["}", ""]
    out += ["abstract final class Radii {"] + [f"  static const double {k} = {float(v)};" for k, v in t["radius"].items()] + ["}", ""]
    out += ["abstract final class Sizes {"] + [f"  static const double {k} = {float(v)};" for k, v in t["sizes"].items()] + ["}", ""]
    out += ["class TypeSpec {", "  const TypeSpec(this.size, this.height, this.weight);", "  final double size;", "  final double height;", "  final int weight;", "}", ""]
    out += ["abstract final class TypeScale {"] + [f"  static const TypeSpec {k} = TypeSpec({float(v['size'])}, {v['height']}, {v['weight']});" for k, v in t["type"].items()] + ["}", ""]
    return "\n".join(out)


def css_block(palette, indent="  "):
    return "\n".join(f"{indent}--fl-color-{re.sub(r'([A-Z])', lambda m: '-' + m.group(1).lower(), n)}: {v};" for n, v in palette.items())


def gen_css(t):
    light, dark = t["colors"]["light"], t["colors"]["dark"]
    parts = ["/* GENERATED by packages/design_system/tools/generate_tokens.py from tokens/tokens.json. Do not edit by hand. */",
             ":root {", css_block(light), "  color-scheme: light dark;"]
    parts += [f"  --fl-space-{k}: {v}px;" for k, v in t["spacing"].items()]
    parts += [f"  --fl-radius-{k}: {v}px;" for k, v in t["radius"].items()]
    parts += [f"  --fl-min-touch-target: {t['sizes']['minTouchTarget']}px;", "}", "",
              "@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"light\"]) {", css_block(dark, "    "), "  }", "}", "",
              ":root[data-theme=\"dark\"] {", css_block(dark), "}", ""]
    return "\n".join(parts)


def gen_report(t):
    rows = ["# Colour contrast report", "", "GENERATED by `packages/design_system/tools/generate_tokens.py`. WCAG 2.x AA: 4.5:1 for text, 3:1 for non-text (icons, control boundaries).", "",
            "| Pair (foreground on background) | Use | Required | Light | Dark |", "|---|---|---|---|---|"]
    for p in t["pairs"]:
        l = contrast(t["colors"]["light"][p["fg"]], t["colors"]["light"][p["bg"]])
        d = contrast(t["colors"]["dark"][p["fg"]], t["colors"]["dark"][p["bg"]])
        rows.append(f"| `{p['fg']}` on `{p['bg']}` | {p['use']} | {p['min']}:1 | {l:.2f} | {d:.2f} |")
    rows += ["", "## Combinations that do NOT meet the bar (never use them)", "", "| Theme | Pair | Ratio | Why |", "|---|---|---|---|"]
    for k in t.get("knownFailures", []):
        pal = t["colors"][k["theme"]]
        rows.append(f"| {k['theme']} | `{k['fg']}` on `{k['bg']}` | {contrast(pal[k['fg']], pal[k['bg']]):.2f} | {k['why']} |")
    rows += ["", "Contrast is necessary, not sufficient: it does not replace testing with a screen reader, large text sizes and real devices.", ""]
    return "\n".join(rows)


def main(argv):
    tokens = json.load(open(SRC, encoding="utf-8"))
    problems = validate(tokens)
    for p in problems:
        print("FAIL  " + p)
    if problems:
        return 1
    outputs = {"dart": gen_dart(tokens), "css": gen_css(tokens), "report": gen_report(tokens)}
    stale = []
    for key, text in outputs.items():
        path = OUT[key]
        if "--check" in argv:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                stale.append(os.path.relpath(path, ROOT))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", encoding="utf-8").write(text)
    if stale:
        print("FAIL  generated files are out of date: " + ", ".join(stale) + " (run generate_tokens.py and commit)")
        return 1
    n = len(tokens["pairs"]) * 2
    print(f"OK    {n} colour-pair checks pass (light and dark); " + ("generated files are up to date" if "--check" in argv else "files generated"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
