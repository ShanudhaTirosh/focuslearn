#!/usr/bin/env python3
"""Generates backend/supabase/tests/050_focus_rules.test.sql from test-vectors/focus.json, so the SQL functions in the migration are held to
exactly the numbers the Python reference and the Dart code pass. Run: gen_focus_pgtap.py [--check]"""
import json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
V = json.load(open(os.path.join(ROOT, "test-vectors", "focus.json"), encoding="utf-8"))
OUT = os.path.join(ROOT, "backend", "supabase", "tests", "050_focus_rules.test.sql")

q = lambda s: "'" + s.replace("'", "''") + "'"
ts = lambda s: f"{q(s)}::timestamptz"
def arr(items, typ):
    return f"array[{', '.join(items)}]::{typ}[]" if items else f"array[]::{typ}[]"

lines = []
def add(sql): lines.append(sql)

for c in V["validated"]:
    add(f"select is(private.focus_validated_seconds({c['planned']}, {ts(c['started'])}, {ts(c['ended'])}, {c['paused']}, {c['reported']}, {ts(c['received'])}), {c['expect']}, {q('validated: ' + c['name'])});")
for c in V["tree"]:
    add(f"select is(private.focus_tree_stage({c['validated']}), {q(c['stage'])}, {q('tree stage at ' + str(c['validated']) + ' seconds')});")
    add(f"select is(private.focus_is_counted({c['validated']}), {'true' if c['counted'] else 'false'}, {q('counted at ' + str(c['validated']) + ' seconds')});")
for c in V["streak"]:
    days = arr([q(d) for d, _ in c["days"]], "date"); secs = arr([str(s) for _, s in c["days"]], "integer")
    add(f"select results_eq($$ select streak, rest_days from private.focus_streak_from({days}, {secs}, {q(c['today'])}::date, {c['goal']}) $$, $$ values ({c['streak']}::integer, {c['rest_days']}::integer) $$, {q('streak: ' + c['name'])});")
for c in V["longest"]:
    days = arr([q(d) for d, _ in c["days"]], "date"); secs = arr([str(s) for _, s in c["days"]], "integer")
    add(f"select is(private.focus_longest_streak_from({days}, {secs}, {c['goal']}), {c['expect']}, {q('longest streak: ' + c['name'])});")
for c in V["achievements"]:
    add(f"select is(private.focus_achievements_for({c['sessions']}::bigint, {c['total_seconds']}::bigint, {c['longest']}), {arr([q(k) for k in c['expect']], 'text')}, {q('achievements: ' + c['name'])});")

text = "\n".join([
    "-- pgTAP: the focus rules in private.* (GENERATED by packages/core/tools/gen_focus_pgtap.py from test-vectors/focus.json: do not edit by hand).",
    "-- The same vectors are passed by the Python reference and the Dart implementation. Run with: bash infra/scripts/run-pgtap.sh",
    "begin;", "create extension if not exists pgtap with schema extensions;", "set local search_path = extensions, public;",
    f"select plan({len(lines)});", ""] + lines + ["", "select * from finish();", "rollback;", ""])

if "--check" in sys.argv:
    good = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
    print("OK    050_focus_rules.test.sql is up to date" if good else "FAIL  050_focus_rules.test.sql is out of date: run gen_focus_pgtap.py")
    sys.exit(0 if good else 1)
open(OUT, "w", encoding="utf-8").write(text)
print("wrote", os.path.relpath(OUT, ROOT), "-", len(lines), "assertions")
