# Helpers sourced by setup.sh. No side effects on load.

# set_env FILE KEY VALUE : replace KEY=... or append it. Safe for backslashes and '=' in values.
set_env() {
  local file="$1" key="$2" val="$3"
  if grep -q "^${key}=" "$file"; then
    K="$key" V="$val" awk 'BEGIN{FS=OFS="="} $1==ENVIRON["K"]{print ENVIRON["K"] "=" ENVIRON["V"]; next} {print}' "$file" > "$file.tmp"
    mv "$file.tmp" "$file"
  else
    printf '%s=%s\n' "$key" "$val" >> "$file"
  fi
  chmod 600 "$file"
}

# set_env_if_present FILE KEY VALUE : only touches keys upstream already defines.
set_env_if_present() {
  if grep -q "^$2=" "$1"; then
    set_env "$1" "$2" "$3"
  else
    printf '[setup] WARN: %s not found in %s, skipped\n' "$2" "$1" >&2
  fi
}

# get_cfg FILE KEY : print value, or nothing if missing.
get_cfg() {
  [ -f "$1" ] || return 0
  grep -E "^$2=" "$1" | tail -n1 | cut -d= -f2- || true
}

# version_ge A B : true if A >= B (version sort).
version_ge() {
  [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | head -n1)" = "$2" ]
}

# render_template TEMPLATE OUT KEY=VAL... : replace @KEY@ placeholders. Values must not contain '&'.
# Fails if any placeholder is left unrendered.
render_template() {
  local tpl="$1" out="$2"; shift 2
  local content kv k v
  content="$(cat "$tpl")"
  for kv in "$@"; do
    k="${kv%%=*}"; v="${kv#*=}"
    content="${content//@${k}@/${v}}"
  done
  if printf '%s' "$content" | grep -Eq '@[A-Z_]+@'; then
    echo "render_template: unrendered placeholder in $tpl" >&2
    return 1
  fi
  printf '%s\n' "$content" > "$out"
}

# render_override GATEWAY HAS_AUTH CAPTCHA CLOUDFLARED_VERSION
# Prints the docker-compose override for the FocusLearn stack. HAS_AUTH and CAPTCHA are 0 or 1.
# CLOUDFLARED_VERSION empty = no tunnel container. Every service appears exactly ONCE (a duplicate YAML key would silently drop settings).
render_override() {
  local gw="$1" has_auth="$2" captcha="$3" cf_ver="${4:-}"
  echo "# Generated by infra/docker/setup.sh (render_override in lib.sh). Do not edit by hand."
  echo "services:"
  echo "  $gw:"
  echo "    ports: !override"
  echo '      - "127.0.0.1:8000:8000"'
  if [ "$has_auth" = 1 ]; then
    echo "  auth:"
    echo "    environment:"
    echo '      GOTRUE_PASSWORD_MIN_LENGTH: "10"'
    echo '      GOTRUE_MAILER_AUTOCONFIRM: "true"'
    if [ "$captcha" = 1 ]; then
      echo '      GOTRUE_SECURITY_CAPTCHA_ENABLED: "true"'
      echo '      GOTRUE_SECURITY_CAPTCHA_PROVIDER: turnstile'
      echo '      GOTRUE_SECURITY_CAPTCHA_SECRET: ${TURNSTILE_SECRET}'
    fi
  fi
  if [ -n "$cf_ver" ]; then
    echo "  cloudflared:"
    echo "    image: cloudflare/cloudflared:$cf_ver"
    echo "    restart: unless-stopped"
    echo '    user: "${CLOUDFLARED_UID}:${CLOUDFLARED_GID}"'
    echo "    command: tunnel --no-autoupdate --config /etc/cloudflared/config.yml run"
    echo "    volumes:"
    echo "      - ./cloudflared:/etc/cloudflared:ro"
    echo "    depends_on:"
    echo "      $gw:"
    echo "        condition: service_started"
  fi
}
