#!/usr/bin/env bash
# Prepare the self-hosted Supabase stack from a PINNED upstream release. Idempotent.
# Upstream files land in infra/docker/stack/ (gitignored). Secrets are generated there by upstream tooling.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STACK="$ROOT/stack"
OVERLAY="$ROOT/.env"
UPSTREAM_REF="$(tr -d '[:space:]' < "$ROOT/UPSTREAM_VERSION")"

# shellcheck source=lib.sh
. "$ROOT/lib.sh"

log() { printf '[setup] %s\n' "$*"; }
die() { printf '[setup] ERROR: %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "missing dependency: $1"; }

need git; need docker; need openssl; need jq; need awk
docker compose version >/dev/null 2>&1 || die "docker compose plugin not found"
cv="$(docker compose version --short)"; cv="${cv#v}"
version_ge "$cv" "2.24.4" || die "docker compose $cv is too old, need >= 2.24.4 for ports override (verify)"

[ -f "$OVERLAY" ] || die "copy infra/docker/.env.example to infra/docker/.env and edit it first"
MODE="$(get_cfg "$OVERLAY" FOCUSLEARN_MODE)"; MODE="${MODE:-local}"
case "$MODE" in local|public) ;; *) die "FOCUSLEARN_MODE must be local or public" ;; esac

FIRST_RUN=0
if [ ! -d "$STACK" ]; then
  log "fetching upstream $UPSTREAM_REF (docker/ directory only)"
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' EXIT
  git clone --filter=blob:none --no-checkout --depth=1 --quiet --branch "$UPSTREAM_REF" \
    https://github.com/supabase/supabase "$tmp/supabase"
  git -C "$tmp/supabase" sparse-checkout init --cone
  git -C "$tmp/supabase" sparse-checkout set docker
  git -C "$tmp/supabase" checkout --quiet
  mkdir -p "$STACK"
  cp -rf "$tmp/supabase/docker/." "$STACK"
  printf 'ref=%s\n' "$UPSTREAM_REF" > "$STACK/.supabase-version"
  cp "$STACK/.env.example" "$STACK/.env"
  chmod 600 "$STACK/.env"
  FIRST_RUN=1
fi

ENVF="$STACK/.env"

if [ "$FIRST_RUN" = 1 ]; then
  log "generating secrets and asymmetric JWT keys with upstream scripts (output contains secrets: keep this terminal private)"
  (cd "$STACK" && sh utils/generate-keys.sh && sh utils/add-new-auth-keys.sh)
fi

# URLs
if [ "$MODE" = "public" ]; then
  API_HOST="$(get_cfg "$OVERLAY" API_HOST)"
  APP_HOST="$(get_cfg "$OVERLAY" APP_HOST)"
  [ -n "$API_HOST" ] || die "API_HOST is required in public mode"
  PUBLIC_URL="https://$API_HOST"
  SITE="https://${APP_HOST:-$API_HOST}"
else
  PUBLIC_URL="http://localhost:8000"
  SITE="http://localhost:3000"
fi
set_env_if_present "$ENVF" SUPABASE_PUBLIC_URL "$PUBLIC_URL"
set_env_if_present "$ENVF" API_EXTERNAL_URL "$PUBLIC_URL"
set_env_if_present "$ENVF" SITE_URL "$SITE"

# Auth hardening: verified email required, no anonymous or phone signup. Skipped with a warning if upstream renamed the key.
set_env_if_present "$ENVF" ENABLE_EMAIL_AUTOCONFIRM false
set_env_if_present "$ENVF" ENABLE_ANONYMOUS_USERS false
set_env_if_present "$ENVF" ENABLE_PHONE_SIGNUP false
set_env_if_present "$ENVF" ENABLE_PHONE_AUTOCONFIRM false

# SMTP (documented upstream variable names)
SMTP_HOST="$(get_cfg "$OVERLAY" SMTP_HOST)"
if [ -n "$SMTP_HOST" ]; then
  for k in SMTP_ADMIN_EMAIL SMTP_HOST SMTP_PORT SMTP_USER SMTP_PASS SMTP_SENDER_NAME; do
    set_env "$ENVF" "$k" "$(get_cfg "$OVERLAY" "$k")"
  done
  log "SMTP configured"
else
  log "SMTP_HOST empty: email features stay unconfigured (step 0.7)"
fi

# Override file, generated by render_override (lib.sh): gateway on loopback, Auth settings, optional Turnstile, optional tunnel container.
GW="$( (cd "$STACK" && docker compose config --services) | grep -Ex 'envoy|kong' | head -n1 || true)"
[ -n "$GW" ] || die "no envoy or kong service found; inspect with: cd infra/docker/stack && docker compose config --services"
OV="$STACK/docker-compose.focuslearn.yml"

HAS_AUTH=0
if (cd "$STACK" && docker compose config --services) | grep -qx auth; then HAS_AUTH=1
else log "WARN: no 'auth' service found: the password-length and captcha settings are NOT applied"; fi

# Turnstile on Auth (signup, login, reset). Refuses to enable with an invalid secret: that would reject every signup.
CAPTCHA=0
TURNSTILE_SECRET="$(get_cfg "$OVERLAY" TURNSTILE_SECRET)"
if [ -n "$TURNSTILE_SECRET" ]; then
  [ "$HAS_AUTH" = 1 ] || die "no 'auth' service found; cannot wire Turnstile"
  rc=0; TURNSTILE_SECRET="$TURNSTILE_SECRET" bash "$ROOT/../scripts/check-turnstile-secret.sh" || rc=$?
  case "$rc" in
    0) ;;
    1) die "Turnstile secret rejected by Cloudflare; fix TURNSTILE_SECRET or leave it empty" ;;
    *) die "could not confirm the Turnstile secret (network?). Not enabling captcha. Retry when online." ;;
  esac
  set_env "$ENVF" TURNSTILE_SECRET "$TURNSTILE_SECRET"
  CAPTCHA=1
  log "Turnstile captcha enabled on Auth"
else
  log "TURNSTILE_SECRET empty: captcha NOT enabled (fine for local mode, required before public signup)"
fi

# Cloudflare Tunnel container (public mode only)
CF_VER=""
if [ "$MODE" = "public" ]; then
  UUID="$(get_cfg "$OVERLAY" TUNNEL_UUID)"
  CRED="$(get_cfg "$OVERLAY" CLOUDFLARED_CREDENTIALS_FILE)"; CRED="${CRED/#\~/$HOME}"
  STUDIO_HOST="$(get_cfg "$OVERLAY" STUDIO_HOST)"
  CF_VER="$(tr -d '[:space:]' < "$ROOT/../cloudflare/CLOUDFLARED_VERSION")"
  [ -n "$UUID" ] && [ -n "$STUDIO_HOST" ] || die "TUNNEL_UUID and STUDIO_HOST are required in public mode"
  [ -f "$CRED" ] || die "CLOUDFLARED_CREDENTIALS_FILE not found: '$CRED'"
  mkdir -p "$STACK/cloudflared"; chmod 700 "$STACK/cloudflared"
  cp "$CRED" "$STACK/cloudflared/$UUID.json"; chmod 600 "$STACK/cloudflared/$UUID.json"
  render_template "$ROOT/../cloudflare/tunnel-config.template.yml" "$STACK/cloudflared/config.yml" \
    "TUNNEL_UUID=$UUID" "API_HOST=$API_HOST" "STUDIO_HOST=$STUDIO_HOST" "GATEWAY=$GW"
  set_env "$ENVF" CLOUDFLARED_UID "$(id -u)"
  set_env "$ENVF" CLOUDFLARED_GID "$(id -g)"
  log "tunnel container configured (cloudflared $CF_VER, verify the tag exists on Docker Hub)"
fi

render_override "$GW" "$HAS_AUTH" "$CAPTCHA" "$CF_VER" > "$OV"

if ! grep -q 'docker-compose.focuslearn.yml' "$ENVF"; then
  (cd "$STACK" && sh run.sh config add focuslearn)
fi

log "done. upstream=$UPSTREAM_REF gateway=$GW mode=$MODE"
log "next: bash infra/scripts/stack.sh start && bash infra/scripts/stack.sh health"
